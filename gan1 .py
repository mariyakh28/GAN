def eval_matrix(model, test_ds, class_names, title):
    loss, acc = model.evaluate(test_ds, verbose=0)

    y_true = np.concatenate([y.numpy() for _, y in test_ds], axis=0).astype(int)
    y_prob = model.predict(test_ds, verbose=0).reshape(-1)
    y_pred = (y_prob >= 0.5).astype(int)

    cm = confusion_matrix(y_true, y_pred)
    rep = classification_report(y_true, y_pred, target_names=class_names, digits=4, zero_division=0)

    print(f"\n===== {title} =====")
    print(f"Test Loss: {loss:.4f}")
    print(f"Test Acc : {acc:.4f}")
    print("Confusion Matrix:\n", cm)
    print("\nClassification Report:\n", rep)
    return acc, cm, rep

