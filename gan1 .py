import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras import layers, models

generator = models.Sequential([
    layers.Input(shape=(latent_dim,)),
    layers.Dense(4*4*256),
    layers.Reshape((4, 4, 256)),

    layers.Conv2DTranspose(128, 4, strides=2, padding="same", activation="relu"),
    layers.Conv2DTranspose(64,  4, strides=2, padding="same", activation="relu"),
    layers.Conv2DTranspose(3,   4, strides=2, padding="same", activation="tanh"),
])

discriminator = models.Sequential([
    layers.Input(shape=img_shape),
    layers.Conv2D(64, 4, strides=2, padding="same"),
    layers.LeakyReLU(0.2),
    layers.Dropout(0.3),

    layers.Conv2D(128, 4, strides=2, padding="same"),
    layers.LeakyReLU(0.2),
    layers.Dropout(0.3),

    layers.Flatten(),
    layers.Dense(1, activation="sigmoid")
])

d_opt = tf.keras.optimizers.Adam(learning_rate=1e-4, beta_1=0.5)
g_opt = tf.keras.optimizers.Adam(learning_rate=2e-4, beta_1=0.5)

discriminator.compile(
    optimizer="adam",
    loss="binary_crossentropy",
)

discriminator.trainable = False
z = layers.Input(shape=(latent_dim,))
fake = generator(z)
validity = discriminator(fake)
gan = models.Model(z, validity)
gan.compile(optimizer=g_opt, loss="binary_crossentropy")

epochs = 50

for epoch in range(epochs):
    for real_imgs in cat_ds:
        bs = tf.shape(real_imgs)[0]

        # Train Discriminator

        discriminator.trainable = True

        noise = tf.random.normal([bs, latent_dim])
        fake_imgs = generator(noise, training=True)


        real_labels = tf.random.uniform([bs, 1], minval=0.9, maxval=1.0)
        fake_labels = tf.random.uniform([bs, 1], minval=0.0, maxval=0.1)

        d_loss_real = discriminator.train_on_batch(real_imgs, real_labels)
        d_loss_fake = discriminator.train_on_batch(fake_imgs, fake_labels)
        d_loss = 0.5 * (d_loss_real + d_loss_fake)


        # Train Generator

        discriminator.trainable = False

        noise = tf.random.normal([bs, latent_dim])
        trick_labels = tf.ones([bs, 1])

        g_loss = gan.train_on_batch(noise, trick_labels)

    if epoch % 10 == 0:
        print(f"Epoch {epoch} | D loss: {float(d_loss):.4f} | G loss: {float(g_loss):.4f}")

